const venues = ["استاد المدينة", "استاد الأبطال", "استاد الجماهير", "استاد البطولة", "استاد النصر", "استاد العالم"];
const matches = [];
const add = (stage, group, teamA, teamB, day, hour = 19) => {
  const a = typeof teamA === "number" ? teams[teamA] : [teamA, "🏳️"];
  const b = typeof teamB === "number" ? teams[teamB] : [teamB, "🏳️"];
  matches.push({
    id: String(matches.length + 1),
    stage,
    group,
    teamA: a[0],
    teamB: b[0],
    teamAFlagEmoji: a[1],
    teamBFlagEmoji: b[1],
    date: `2026-${day < 19 ? "06" : "07"}-${String(day < 19 ? day : day - 18).padStart(2, "0")}`,
    timeUTC: `${String(hour).padStart(2, "0")}:00`,
    venue: venues[matches.length % venues.length],
    status: "upcoming",
    scoreA: null,
    scoreB: null
  });
};

for (let group = 0; group < 12; group += 1) {
  const base = group * 4;
  [[0, 1], [2, 3], [0, 2], [3, 1], [3, 0], [1, 2]].forEach(([a, b], round) => {
    add("دور المجموعات", `المجموعة ${"ABCDEFGHIJKL"[group]}`, base + a, base + b, 11 + Math.floor((group * 6 + round) / 4), [16, 19, 22][round % 3]);
  });
}
for (let i = 0; i < 16; i += 1) add("دور الـ32", "", `متصدر مجموعة ${i + 1}`, `متأهل ${i + 17}`, 29 + Math.floor(i / 3), 19 + (i % 2) * 3);
for (let i = 0; i < 8; i += 1) add("دور الـ16", "", `فائز مباراة ${73 + i * 2}`, `فائز مباراة ${74 + i * 2}`, 35 + Math.floor(i / 2), 19 + (i % 2) * 3);
for (let i = 0; i < 4; i += 1) add("ربع النهائي", "", `فائز دور الـ16 ${i * 2 + 1}`, `فائز دور الـ16 ${i * 2 + 2}`, 40 + Math.floor(i / 2), 19 + (i % 2) * 3);
for (let i = 0; i < 2; i += 1) add("نصف النهائي", "", `فائز ربع النهائي ${i * 2 + 1}`, `فائز ربع النهائي ${i * 2 + 2}`, 44 + i, 22);
add("تحديد المركز الثالث", "", "خاسر نصف النهائي 1", "خاسر نصف النهائي 2", 47, 19);
add("النهائي", "", "فائز نصف النهائي 1", "فائز نصف النهائي 2", 48, 22);
mkdirSync("src/data", { recursive: true });
writeFileSync("src/data/matches.json", `${JSON.stringify(matches, null, 2)}\n`);
console.log(`Generated ${matches.length} matches.`);
